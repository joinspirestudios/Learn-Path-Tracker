#!/usr/bin/env node
/**
 * Generates apps/mobile/src/shared/api-contracts.generated.js from the
 * single source of truth in src/shared-api-contracts.js.
 *
 * This keeps the mobile skin's API contract constants in sync with the web
 * brain without hand-maintained duplication. It never changes endpoint paths,
 * never adds new Vercel routes, and never embeds secrets.
 *
 * Run from the repo root: `npm run generate:mobile-contracts`.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  API_ENDPOINTS,
  API_ROUTE_GROUPS,
  API_CONTRACTS,
  SHARED_PRIVACY_CONSTRAINTS,
} from '../src/shared-api-contracts.js';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const outPath = resolve(root, 'apps/mobile/src/shared/api-contracts.generated.js');

const header = '// Generated by scripts/generate-mobile-contracts.mjs. Do not edit by hand.\n'
  + '// Source of truth: src/shared-api-contracts.js\n'
  + '// Regenerate with: npm run generate:mobile-contracts\n';

function emit(name, value){
  return 'export const ' + name + ' = ' + JSON.stringify(value, null, 2) + ';\n';
}

const body = [
  header,
  emit('API_ENDPOINTS', API_ENDPOINTS),
  emit('API_ROUTE_GROUPS', API_ROUTE_GROUPS),
  emit('API_CONTRACTS', API_CONTRACTS),
  emit('SHARED_PRIVACY_CONSTRAINTS', SHARED_PRIVACY_CONSTRAINTS),
].join('\n');

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, body, 'utf8');

console.log('Generated ' + outPath);
