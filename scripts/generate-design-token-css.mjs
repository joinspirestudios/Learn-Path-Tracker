import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { designTokensToCssRoot } from '../src/design-token-css.js';

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(rootDir, 'src/generated/design-tokens.css');
const css = '/* Generated by scripts/generate-design-token-css.mjs. Do not edit by hand. */\n'
  + designTokensToCssRoot();

await mkdir(dirname(outputPath), { recursive:true });
await writeFile(outputPath, css, 'utf8');
console.log('Generated ' + outputPath);
