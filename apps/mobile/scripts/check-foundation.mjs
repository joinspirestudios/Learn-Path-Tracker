  'src/core/mobileProofMappers.js',
  'src/core/mobilePublicProgressMappers.js',
  'src/services/dayLogRepository.js',
  'src/services/mobileProofRepository.js',
  'src/services/mobilePublicProgressRepository.js',
  'src/components/MobileSyncBanner.js',
